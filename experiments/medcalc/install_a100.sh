#!/usr/bin/env bash
# Build the Linux CUDA environment the MedCalc run needs on an A100.
# Run this on the rented machine, from any working directory.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
ENV=${MEDCALC_ENV:-$ROOT/.venv-a100}
HERE=$(cd "$(dirname "$0")" && pwd)

if [[ "$(uname -s)" != "Linux" ]]; then
  echo "install_a100.sh is for the rented Linux GPU. This machine is $(uname -s)." >&2
  echo "Copy the repo to the A100 and run: bash experiments/medcalc/install_a100.sh" >&2
  exit 1
fi

pick_python() {
  if [[ -n "${PYTHON:-}" ]]; then
    printf '%s\n' "$PYTHON"
    return
  fi
  local candidate
  for candidate in python3.11 python3; do
    if command -v "$candidate" >/dev/null 2>&1 \
        && "$candidate" -c 'import sys; raise SystemExit(0 if sys.version_info[:2] == (3, 11) else 1)'; then
      printf '%s\n' "$candidate"
      return
    fi
  done
  echo "Python 3.11 is required. Install it, or set PYTHON=/path/to/python3.11." >&2
  exit 1
}

PY=$(pick_python)
echo "using $PY ($("$PY" -V))"
"$PY" -m venv "$ENV"
"$ENV/bin/python" -m pip install -U pip setuptools wheel
"$ENV/bin/python" -m pip install -r "$HERE/requirements.txt"

# Clone the pinned forks and apply the tandem patches. --install is not used:
# this repo's installer expects env/constraints.txt, which is not checked in.
PYTHON="$ENV/bin/python" bash "$ROOT/third_party/apply_patches.sh"
VLLM_USE_PRECOMPILED=1 "$ENV/bin/python" -m pip install -e "$ROOT/third_party/vllm" --no-build-isolation
if ! "$ENV/bin/python" -c "import vllm; from vllm import _C" >/dev/null 2>&1; then
  echo "editable vLLM is missing the wheel's compiled extensions; copying them"
  stage=$(mktemp -d)
  "$ENV/bin/python" -m pip download 'vllm==0.19.1' --no-deps -d "$stage"
  "$ENV/bin/python" -c "import glob, zipfile; zipfile.ZipFile(glob.glob('$stage/vllm-*.whl')[0]).extractall('$stage/x')"
  cp "$stage"/x/vllm/*.so "$ROOT/third_party/vllm/vllm/"
  mkdir -p "$ROOT/third_party/vllm/vllm/vllm_flash_attn"
  cp "$stage"/x/vllm/vllm_flash_attn/*.so "$ROOT/third_party/vllm/vllm/vllm_flash_attn/"
  rm -rf "$stage"
fi
"$ENV/bin/python" -m pip install -e "$ROOT/third_party/verl" -c "$HERE/constraints.txt"
"$ENV/bin/python" -m pip install 'TransferQueue==0.1.8'

"$ENV/bin/python" - <<'PY'
from vllm.config import TandemConfig
from vllm.v1.sample.tandem_sampler import TandemSampler
import verl
import transfer_queue
from verl.workers.utils.losses import _apply_tandem_senior_gate
print("vllm fork OK", TandemConfig, TandemSampler)
print("verl fork OK", verl.__file__)
PY

cat > "$HERE/env.sh" <<EOF
# Generated by install_a100.sh. Safe to delete and regenerate.
TANDEM_ENV_BIN=$ENV/bin
export PATH="\$TANDEM_ENV_BIN:\$PATH"
export BASE_MODEL=\${BASE_MODEL:-Qwen/Qwen3-4B-Instruct-2507}
export CKPT_ROOT=\${CKPT_ROOT:-$ROOT/checkpoints}
export DATA_ROOT=\${DATA_ROOT:-$ROOT/data}
export PROJECT_NAME=\${PROJECT_NAME:-medcalc-trlvr}
export HF_HOME=\${HF_HOME:-$ROOT/.cache/huggingface}
export WANDB_MODE=\${WANDB_MODE:-offline}
export RAY_ENABLE_UV_RUN_RUNTIME_ENV=0
export TQ_STORAGE_UNITS=\${TQ_STORAGE_UNITS:-1}
export DATA_WORKERS=\${DATA_WORKERS:-2}
export AGENT_WORKERS=\${AGENT_WORKERS:-4}
export OMP_NUM_THREADS=\${OMP_NUM_THREADS:-1}
export RAY_DEFAULT_OBJECT_STORE_MAX_MEMORY_BYTES=\${RAY_DEFAULT_OBJECT_STORE_MAX_MEMORY_BYTES:-4294967296}
export TOKENIZERS_PARALLELISM=false
export HYDRA_FULL_ERROR=1
export VLLM_WORKER_MULTIPROC_METHOD=spawn
export XDG_CACHE_HOME=\${XDG_CACHE_HOME:-$ROOT/.cache}
export VLLM_CONFIG_ROOT=\${VLLM_CONFIG_ROOT:-\$XDG_CACHE_HOME/vllm}
mkdir -p "\$VLLM_CONFIG_ROOT" "\$HF_HOME"
EOF

echo
echo "environment: $ENV"
echo "next: bash experiments/medcalc/prepare.sh"
